Console.BackgroundColor = ConsoleColor.White;
//Comando repetição for - crescente

for(int i=1; i<=40; i++)
{
    Console.ForegroundColor = ConsoleColor.Green;
    Console.WriteLine(i);
}

//Comando repetição for - decrescente

for (int i = 40; i >= 1; i--)
{
    Console.ForegroundColor = ConsoleColor.Green;
    Console.WriteLine(i);
}